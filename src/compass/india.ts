function shuffled<T>(xs: T[], seed: number): T[] {
  const a = xs.slice();
  let s = seed;
  for (let i = a.length - 1; i > 0; i--) { s = (s * 16807) % 2147483647; const j = s % (i + 1); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

/** Drop a leading “Agreeing:” or “Disagreeing looks like”: the page already labels each box. */
const tidy = (t: string) => { const x = t.replace(/^(Agreeing|Disagreeing)( looks like)?:?\s*/, ''); return x.charAt(0).toUpperCase() + x.slice(1); };
export const INDIA_QUESTIONS: IQuestion[] = shuffled(RAW.map(([axis, dir, topic, text, cue, agree, disagree], i) => ({ id: `n${i + 1}`, axis, dir, topic, text, cue, agree: tidy(agree), disagree: tidy(disagree) })), 20261101);

export type IAnswers = Record<string, number | null>;
export function indiaScore(answers: IAnswers): Scores {
  const out = {} as Scores;
  for (const a of AXES) {
    const qs = INDIA_QUESTIONS.filter((q) => q.axis === a.id && answers[q.id] != null);
    if (!qs.length) { out[a.id] = null; continue; }
    const sum = qs.reduce((s, q) => s + (answers[q.id] as number) * q.dir, 0);
    out[a.id] = Math.round(50 + (50 * sum) / (2 * qs.length));
  }
  return out;
}

