#!/usr/bin/env node
/**
 * Emits the SQL seed for the `pens` table straight from src/game/pens.ts.
 *
 * The client is the source of truth for pen physics — it has to be, the
 * simulation runs there — so rather than maintain the numbers twice, the DB
 * catalog is generated. Run it after touching the roster:
 *
 *   node scripts/gen-pen-seed.mjs > supabase/migrations/0002_seed_pens.sql
 */
import { PENS } from '../src/game/pens.ts';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const rows = PENS.map((p, i) =>
  [
    q(p.id),
    q(p.name),
    q(p.brand),
    p.tier,
    q(p.blurb),
    (p.mass * 1000).toFixed(2), // grams in the DB, kg in the engine
    (p.length * 100).toFixed(2), // cm
    (p.radius * 100).toFixed(3), // cm
    p.friction,
    p.restitution,
    p.balance,
    q(p.weightLabel),
    q(p.woodLabel),
    q(p.habitLabel),
    q(p.bodyColor),
    q(p.capColor),
    q(p.gripColor),
    q(p.accentColor),
    q(p.barrelStyle),
    p.transparent,
    p.unlockPoints,
    i,
  ].join(', '),
);

process.stdout.write(`-- GENERATED by scripts/gen-pen-seed.mjs — do not edit by hand.
insert into public.pens (
  id, name, brand, tier, blurb,
  mass, length, radius, friction, restitution, balance,
  weight_label, wood_label, habit_label,
  body_color, cap_color, grip_color, accent_color,
  barrel_style, transparent, unlock_points, sort_order
) values
${rows.map((r) => `  (${r})`).join(',\n')}
on conflict (id) do update set
  name          = excluded.name,
  brand         = excluded.brand,
  tier          = excluded.tier,
  blurb         = excluded.blurb,
  mass          = excluded.mass,
  length        = excluded.length,
  radius        = excluded.radius,
  friction      = excluded.friction,
  restitution   = excluded.restitution,
  balance       = excluded.balance,
  weight_label  = excluded.weight_label,
  wood_label    = excluded.wood_label,
  habit_label   = excluded.habit_label,
  body_color    = excluded.body_color,
  cap_color     = excluded.cap_color,
  grip_color    = excluded.grip_color,
  accent_color  = excluded.accent_color,
  barrel_style  = excluded.barrel_style,
  transparent   = excluded.transparent,
  unlock_points = excluded.unlock_points,
  sort_order    = excluded.sort_order;
`);
